def write_pairing_frame_header(
    path: Path,
    *,
    device_code: str,
    frame: bytes,
) -> None:
    if len(frame) != PAIRING_FRAME_SIZE:
        raise ValueError(
            f"expected {PAIRING_FRAME_SIZE} pairing bytes, got {len(frame)}"
        )
    lines = [
        "#pragma once",
        "",
        "#include <Arduino.h>",
        "",
        "// Generated by the factory tool for this public device code.",
        f'constexpr char kFactoryPairingDeviceCode[] = "{device_code}";',
        f"constexpr size_t kFactoryPairingFrameSize = {len(frame)};",
        "const uint8_t kFactoryPairingFrame[kFactoryPairingFrameSize] "
        "PROGMEM = {",
    ]
    for start in range(0, len(frame), 16):
        chunk = frame[start : start + 16]
        lines.append(
            "    " + ", ".join(f"0x{value:02X}" for value in chunk) + ","
        )
    lines.extend(["};", ""])
    _write_private_text(path, "\n".join(lines))


def render_a4_label_sheets(
    labels: Sequence[Image.Image],
) -> list[Image.Image]:
    sheets: list[Image.Image] = []
    for page_start in range(0, len(labels), 10):
        sheet = Image.new("RGB", (A4_WIDTH, A4_HEIGHT), "white")
        cell_width = 1080
        cell_height = 630
        horizontal_gap = 80
        vertical_gap = 40
        start_x = (A4_WIDTH - cell_width * 2 - horizontal_gap) // 2
        start_y = 95
        for index, label in enumerate(labels[page_start : page_start + 10]):
            row, column = divmod(index, 2)
            resized = label.resize(
                (cell_width, cell_height),
                Image.Resampling.LANCZOS,
            )
            x = start_x + column * (cell_width + horizontal_gap)
            y = start_y + row * (cell_height + vertical_gap)
            sheet.paste(resized, (x, y))
        sheets.append(sheet)
    return sheets


def _write_manifest(
    *,
    output_dir: Path,
    batch_id: str,
    created_at: str,
    artifacts: Sequence[FactoryDeviceArtifact],
    app_env: str,
) -> None:
    payload = {
        "schema_version": 2,
        "batch_id": batch_id,
        "created_at": created_at,
        "app_env": app_env,
        "manifest_contains_device_secrets": False,
        "devices": [asdict(artifact) for artifact in artifacts],
    }
    _write_private_text(
        output_dir / "manifest.json",
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
    )
    csv_path = output_dir / "manifest.csv"
    descriptor = os.open(
        csv_path,
        os.O_WRONLY | os.O_CREAT | os.O_EXCL,
        0o600,
    )
    with os.fdopen(descriptor, "w", encoding="utf-8", newline="") as output:
        writer = csv.DictWriter(
            output,
            fieldnames=[
                "device_code",
                "panel_model",
                "secret_version",
                "mini_program_code_ready",
                "firmware_header",
                "mini_program_code",
                "pairing_frame_header",
                "pairing_frame_preview",
                "printable_label",
            ],
        )
        writer.writeheader()
        for artifact in artifacts:
            writer.writerow(asdict(artifact))


async def _device_code_exists(
    session: AsyncSession,
    device_code: str,
) -> bool:
    return (
        await session.scalar(
            select(func.count())
            .select_from(Device)
            .where(Device.device_code == device_code)
        )
        or 0
    ) > 0


async def _allocate_codes(
    *,
    session: AsyncSession,
    count: int,
    prefix: str,
    explicit_codes: Sequence[str],
) -> list[str]:
    if explicit_codes:
        codes = [validate_device_code(code) for code in explicit_codes]
        if len(codes) != len(set(codes)):
            raise RuntimeError("device codes in this batch must be unique")
        for code in codes:
            if await _device_code_exists(session, code):
                raise RuntimeError(f"device code is already registered: {code}")
        return codes

    if not 1 <= count <= MAX_BATCH_SIZE:
        raise ValueError(f"batch count must be between 1 and {MAX_BATCH_SIZE}")
    codes: list[str] = []
    attempts = 0
    while len(codes) < count and attempts < count * 100:
        attempts += 1
        candidate = generate_device_code(prefix)
        if candidate in codes or await _device_code_exists(session, candidate):
            continue
        codes.append(candidate)
    if len(codes) != count:
        raise RuntimeError("could not allocate enough unique device codes")
    return codes


async def create_factory_batch(
    *,
    output_dir: Path,
    count: int = 1,
    prefix: str,
    explicit_codes: Sequence[str] = (),
    skip_mini_program_code: bool = False,
    session_factory: SessionFactory = AsyncSessionFactory,
    code_generator: CodeGenerator = generate_mini_program_code,
) -> list[FactoryDeviceArtifact]:
    output = output_dir.expanduser().resolve()
    if output.exists():
        raise RuntimeError(f"refusing to use existing output directory: {output}")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.mkdir(mode=0o700)

    labels: list[Image.Image] = []
    artifacts: list[FactoryDeviceArtifact] = []
    created_at = datetime.now(timezone.utc).isoformat()
    batch_id = (
        f"factory-{datetime.now(timezone.utc):%Y%m%dT%H%M%SZ}-"
        f"{secrets.token_hex(3)}"
    )
    try:
        async with session_factory() as session:
            codes = await _allocate_codes(
                session=session,
                count=count,
                prefix=prefix,
                explicit_codes=explicit_codes,
            )
            for code in codes:
                secret = secrets.token_hex(32)
                code_png = (
                    None
                    if skip_mini_program_code
                    else await code_generator(code)
                )
                device_dir = output / code
                device_dir.mkdir(mode=0o700)
                header_path = device_dir / "device_secrets.h"
                write_factory_header(header_path, code, secret)

                code_path: Path | None = None
                if code_png is not None:
                    code_path = device_dir / "mini-program-code.png"
                    code_path.write_bytes(code_png)
                    code_path.chmod(0o600)

                pairing_header_path: Path | None = None
                pairing_preview_path: Path | None = None
                if code_png is not None:
                    pairing_image = render_pairing_frame(
                        device_code=code,
                        mini_program_code_png=code_png,
                    )
                    pairing_frame = encode_f53(pairing_image)
                    pairing_preview_path = (
                        device_dir / "factory-pairing-frame.png"
                    )
                    pairing_image.save(
                        pairing_preview_path,
                        format="PNG",
                        optimize=True,
                    )
                    pairing_preview_path.chmod(0o600)
                    pairing_header_path = (
                        device_dir / "factory_pairing_frame.h"
                    )
                    write_pairing_frame_header(
                        pairing_header_path,
                        device_code=code,
                        frame=pairing_frame,
                    )

                label = render_device_label(
                    device_code=code,
                    mini_program_code_png=code_png,
                )
                label_path = device_dir / "device-label.png"
                label.save(label_path, format="PNG", optimize=True, dpi=(300, 300))
                label_path.chmod(0o600)
                labels.append(label)

                session.add(
                    Device(
                        device_code=code,
                        device_secret_hash=device_secret_hash(secret),
                        device_secret_ciphertext=encrypt_device_secret(
                            secret,
                            code,
                        ),
                        secret_version=1,
                        mini_program_code_png=code_png,
                        mini_program_code_updated_at=(
                            utc_now() if code_png is not None else None
                        ),
                        status=DeviceStatus.UNBOUND,
                    )
                )
                artifacts.append(
                    FactoryDeviceArtifact(
                        device_code=code,
                        panel_model="GDEM075F53",
                        secret_version=1,
                        mini_program_code_ready=code_png is not None,
                        firmware_header=str(
                            header_path.relative_to(output)
                        ),
                        mini_program_code=(
                            str(code_path.relative_to(output))
                            if code_path is not None
                            else None
                        ),
                        pairing_frame_header=(
                            str(pairing_header_path.relative_to(output))
                            if pairing_header_path is not None
                            else None
                        ),
                        pairing_frame_preview=(
                            str(pairing_preview_path.relative_to(output))
                            if pairing_preview_path is not None
                            else None
                        ),
                        printable_label=str(
                            label_path.relative_to(output)
                        ),
                    )
                )

            _write_manifest(
                output_dir=output,
                batch_id=batch_id,
                created_at=created_at,
                artifacts=artifacts,
                app_env=get_settings().app_env,
            )
            sheets = render_a4_label_sheets(labels)
            sheet_pdf = output / "labels-a4.pdf"
            for page_number, sheet in enumerate(sheets, start=1):
                sheet_png = output / f"labels-a4-page-{page_number:02d}.png"
                sheet.save(
                    sheet_png,
                    format="PNG",
                    optimize=True,
                    dpi=(300, 300),
                )
                sheet_png.chmod(0o600)
            sheets[0].save(
                sheet_pdf,
                format="PDF",
                resolution=300,
                save_all=True,
                append_images=sheets[1:],
            )
            sheet_pdf.chmod(0o600)
            await session.commit()
    except BaseException:
        shutil.rmtree(output)
        raise
    return artifacts


async def inspect_release_readiness(
    *,
    device_code: str,
    artifact_dir: Path | None,
    hardware_passed: bool,
    nvs_cleared: bool,
    session_factory: SessionFactory = AsyncSessionFactory,
) -> list[ReleaseCheck]:
    code = validate_device_code(device_code)
    async with session_factory() as session:
        device = await session.scalar(
            select(Device).where(Device.device_code == code)
        )
        if device is None:
            return [
                ReleaseCheck(
                    "production registration",
                    False,
                    "device is not registered",
                )
            ]
        pending_sessions = (
            await session.scalar(
                select(func.count())
                .select_from(DeviceProvisioningSession)
                .where(
                    DeviceProvisioningSession.device_id == device.id,
                    DeviceProvisioningSession.status
                    == DeviceProvisioningStatus.PENDING,
                )
            )
            or 0
        )

    checks = [
        ReleaseCheck(
            "device is unbound",
            device.status == DeviceStatus.UNBOUND
            and device.household_id is None,
            f"status={device.status.value}, household_bound="
            f"{device.household_id is not None}",
        ),
        ReleaseCheck(
            "encrypted factory secret",
            bool(device.device_secret_ciphertext),
            "encrypted secret is present"
            if device.device_secret_ciphertext
            else "encrypted secret is missing",
        ),
        ReleaseCheck(
            "mini program code",
            bool(device.mini_program_code_png),
            "mini program code is cached"
            if device.mini_program_code_png
            else "mini program code is missing",
        ),
        ReleaseCheck(
            "pending provisioning sessions",
            pending_sessions == 0,
            f"pending sessions={pending_sessions}",
        ),
    ]

    if artifact_dir is None:
        checks.append(
            ReleaseCheck(
                "factory artifacts",
                False,
                "--artifact-dir is required",
            )
        )
    else:
        directory = artifact_dir.expanduser().resolve()
        header = directory / "device_secrets.h"
        pairing_header = directory / "factory_pairing_frame.h"
        pairing_preview = directory / "factory-pairing-frame.png"
        label = directory / "device-label.png"
        header_valid = False
        header_private = False
        pairing_header_valid = False
        pairing_header_private = False
        if header.is_file():
            content = header.read_text(encoding="utf-8")
            header_valid = f'kDeviceCode[] = "{code}"' in content
            header_private = (header.stat().st_mode & 0o077) == 0
        if pairing_header.is_file():
            pairing_content = pairing_header.read_text(encoding="utf-8")
            pairing_header_valid = (
                f'kFactoryPairingDeviceCode[] = "{code}"'
                in pairing_content
                and f"kFactoryPairingFrameSize = {PAIRING_FRAME_SIZE}"
                in pairing_content
            )
            pairing_header_private = (
                pairing_header.stat().st_mode & 0o077
            ) == 0
        checks.extend(
            [
                ReleaseCheck(
                    "firmware header",
                    header_valid,
                    "header matches device code"
                    if header_valid
                    else "header is missing or belongs to another device",
                ),
                ReleaseCheck(
                    "header permissions",
                    header_private,
                    "header is owner-only"
                    if header_private
                        else "header permissions must be 0600",
                ),
                ReleaseCheck(
                    "pairing frame header",
                    pairing_header_valid,
                    "pairing frame matches device code"
                    if pairing_header_valid
                    else "pairing frame is missing or belongs to another device",
                ),
                ReleaseCheck(
                    "pairing frame permissions",
                    pairing_header_private,
                    "pairing frame header is owner-only"
                    if pairing_header_private
                    else "pairing frame header permissions must be 0600",
                ),
                ReleaseCheck(
                    "pairing frame preview",
                    pairing_preview.is_file(),
                    "pairing frame preview is present"
                    if pairing_preview.is_file()
                    else "factory-pairing-frame.png is missing",
                ),
                ReleaseCheck(
                    "printable label",
                    label.is_file(),
                    "label file is present"
                    if label.is_file()
                    else "device-label.png is missing",
                ),
            ]
        )

    checks.extend(
        [
            ReleaseCheck(
                "hardware QA",
                hardware_passed,
                "hardware QA confirmed"
                if hardware_passed
                else "pass --confirm-hardware-pass after physical QA",
            ),
            ReleaseCheck(
                "device NVS cleared",
                nvs_cleared,
                "NVS clear confirmed"
                if nvs_cleared
                else "pass --confirm-nvs-cleared only after physical reset",
            ),
        ]
    )
    return checks


async def list_factory_devices(
    *,
    limit: int,
    session_factory: SessionFactory = AsyncSessionFactory,
) -> list[dict[str, Any]]:
    if not 1 <= limit <= 1000:
        raise ValueError("limit must be between 1 and 1000")
    async with session_factory() as session:
        devices = list(
            (
                await session.scalars(
                    select(Device)
                    .order_by(Device.created_at.desc())
                    .limit(limit)
                )
            ).all()
        )
    return [
        {
            "device_code": device.device_code,
            "status": device.status.value,
            "bound": device.household_id is not None,
            "mini_program_code_ready": (
                device.mini_program_code_png is not None
            ),
            "secret_version": device.secret_version,
            "last_seen_at": (
                device.last_seen_at.isoformat()
                if device.last_seen_at is not None
                else "-"
            ),
        }
        for device in devices
    ]


def _print_artifacts(
    output_dir: Path,
    artifacts: Sequence[FactoryDeviceArtifact],
) -> None:
    print(f"Factory batch created: {output_dir.expanduser().resolve()}")
    print(f"Devices registered: {len(artifacts)}")
    for artifact in artifacts:
        print(
            f"  {artifact.device_code}  "
            f"mini-program-code="
            f"{'ready' if artifact.mini_program_code_ready else 'skipped'}"
        )
    print("No device secret was printed or written to the manifest.")


def _print_checks(checks: Sequence[ReleaseCheck]) -> bool:
    passed = all(check.passed for check in checks)
    for check in checks:
        marker = "PASS" if check.passed else "FAIL"
        print(f"[{marker}] {check.name}: {check.detail}")
    print(f"RELEASE CHECK: {'PASS' if passed else 'FAIL'}")
    return passed


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Create and inspect sellable ESP32 e-paper device identities. "
            "Secrets are never printed."
        )
    )
    subparsers = parser.add_subparsers(dest="action", required=True)

    create = subparsers.add_parser(
        "create-batch",
        help="register devices and create firmware, code, label, and manifest files",
    )
    create.add_argument(
        "--output-dir",
        required=True,
        type=Path,
        help="new private directory; existing directories are refused",
    )
    create.add_argument(
        "--count",
        type=int,
        default=1,
        help=f"number of random device codes, 1-{MAX_BATCH_SIZE}",
    )
    create.add_argument(
        "--code-prefix",
        default=f"rfm-{datetime.now(timezone.utc):%y}",
        help="prefix used before a random six-character suffix",
    )
    create.add_argument(
        "--device-code",
        action="append",
        default=[],
        help="explicit device code; repeat for a batch (overrides --count)",
    )
    create.add_argument(
        "--skip-mini-program-code",
        action="store_true",
        help="development only; creates a non-sellable placeholder label",
    )

    listing = subparsers.add_parser(
        "list",
        help="list public device management state without secrets",
    )
    listing.add_argument("--limit", type=int, default=100)

    release = subparsers.add_parser(
        "release-check",
        help="fail unless database, artifacts, hardware, and NVS are sale-ready",
    )
    release.add_argument("--device-code", required=True)
    release.add_argument(
        "--artifact-dir",
        required=True,
        type=Path,
        help="device subdirectory produced by create-batch",
    )
    release.add_argument(
        "--confirm-hardware-pass",
        action="store_true",
        help="confirm board, display, BLE, Wi-Fi, and frame QA passed",
    )
    release.add_argument(
        "--confirm-nvs-cleared",
        action="store_true",
        help="confirm test Wi-Fi and household configuration were cleared",
    )
    return parser


async def _run(args: argparse.Namespace) -> int:
    if args.action == "create-batch":
        artifacts = await create_factory_batch(
            output_dir=args.output_dir,
            count=args.count,
            prefix=args.code_prefix,
            explicit_codes=args.device_code,
            skip_mini_program_code=args.skip_mini_program_code,
        )
        _print_artifacts(args.output_dir, artifacts)
        return 0
    if args.action == "list":
        devices = await list_factory_devices(limit=args.limit)
        print(
            "DEVICE CODE | STATUS | BOUND | MINI CODE | SECRET VERSION | "
            "LAST SEEN"
        )
        for device in devices:
            print(
                f"{device['device_code']} | {device['status']} | "
                f"{'yes' if device['bound'] else 'no'} | "
                f"{'ready' if device['mini_program_code_ready'] else 'missing'}"
                f" | {device['secret_version']} | {device['last_seen_at']}"
            )
        return 0
    checks = await inspect_release_readiness(
        device_code=args.device_code,
        artifact_dir=args.artifact_dir,
        hardware_passed=args.confirm_hardware_pass,
        nvs_cleared=args.confirm_nvs_cleared,
    )
    return 0 if _print_checks(checks) else 1


def main() -> None:
    parser = _build_parser()
    args = parser.parse_args()
    try:
        exit_code = asyncio.run(_run(args))
    except Exception as error:
        parser.exit(1, f"factory tool failed: {error}\n")
    raise SystemExit(exit_code)


if __name__ == "__main__":
    main()
