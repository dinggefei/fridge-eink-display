def validate_device_code(device_code: str) -> str:
    normalized = device_code.strip()
    if (
        not 3 <= len(normalized) <= 32
        or not normalized.isascii()
        or not DEVICE_CODE_PATTERN.fullmatch(normalized)
    ):
        raise ValueError(
            "device code must be 3-32 lowercase ASCII letters, digits, "
            "or internal hyphens"
        )
    return normalized


def validate_code_prefix(prefix: str) -> str:
    normalized = validate_device_code(prefix)
    if len(normalized) > 25:
        raise ValueError(
            "device code prefix must be at most 25 characters so a unique "
            "suffix can be appended"
        )
    return normalized


def generate_device_code(prefix: str) -> str:
    normalized_prefix = validate_code_prefix(prefix)
    suffix = "".join(
        secrets.choice(DEVICE_SUFFIX_ALPHABET) for _ in range(6)
    )
    return validate_device_code(f"{normalized_prefix}-{suffix}")


def _find_font_path() -> str:
    configured = os.getenv("RFM_CJK_FONT")
    candidates = [
        configured,
        "/System/Library/Fonts/PingFang.ttc",
        "/System/Library/Fonts/STHeiti Medium.ttc",
        "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc",
        "/usr/share/fonts/truetype/noto/NotoSansCJK-Regular.ttc",
        "/usr/share/fonts/truetype/wqy/wqy-zenhei.ttc",
    ]
    for candidate in candidates:
        if candidate and Path(candidate).is_file():
            return candidate
    raise RuntimeError(
        "No CJK font found. Set RFM_CJK_FONT to a Chinese font file."
    )


def _font(size: int, *, bold: bool = False) -> ImageFont.FreeTypeFont:
    path = _find_font_path()
    index = 1 if bold and path.endswith((".ttc", ".otc")) else 0
    return ImageFont.truetype(path, size=size, index=index)


def _write_private_text(path: Path, content: str) -> None:
    descriptor = os.open(
        path,
        os.O_WRONLY | os.O_CREAT | os.O_EXCL,
        0o600,
    )
    with os.fdopen(descriptor, "w", encoding="utf-8") as output:
        output.write(content)


def write_factory_header(path: Path, device_code: str, secret: str) -> None:
    code = validate_device_code(device_code)
    if len(secret) < 64:
        raise ValueError("factory device secret must contain at least 64 characters")
    _write_private_text(
        path,
        (
            "#pragma once\n\n"
            "// Generated by the factory tool. Never commit or share this file.\n"
            f'constexpr char kDeviceCode[] = "{code}";\n'
            f'constexpr char kDeviceSecret[] = "{secret}";\n'
        ),
    )


